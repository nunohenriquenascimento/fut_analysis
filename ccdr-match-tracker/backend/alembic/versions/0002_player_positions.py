"""Replace broad positions with the seven roster positions, preserving rows.

Manually reviewed: PostgreSQL enum changes are not reliably autogenerated.
The replacement and cast run in Alembic's transaction, with no commit halfway.
Downgrade refuses positions without an exact legacy equivalent to avoid loss.
"""
from alembic import op

revision = "0002"
down_revision = "0001"
branch_labels = None
depends_on = None


def upgrade() -> None:
    op.execute("CREATE TYPE player_position_new AS ENUM ('GR', 'DC', 'ALA', 'MDC', 'MC', 'PL', 'UNIVERSAL')")
    op.execute("""
        ALTER TABLE players ALTER COLUMN position TYPE player_position_new
        USING (CASE position::text
            WHEN 'GOALKEEPER' THEN 'GR'
            WHEN 'DEFENDER' THEN 'DC'
            WHEN 'MIDFIELDER' THEN 'MC'
            WHEN 'FORWARD' THEN 'PL'
        END)::player_position_new
    """)
    op.execute("DROP TYPE player_position")
    op.execute("ALTER TYPE player_position_new RENAME TO player_position")


def downgrade() -> None:
    # Hold the table lock through the check and cast: no concurrent new values.
    op.execute("LOCK TABLE players IN ACCESS EXCLUSIVE MODE")
    op.execute("""
        DO $$ BEGIN
            IF EXISTS (SELECT 1 FROM players WHERE position::text IN ('ALA', 'MDC', 'UNIVERSAL')) THEN
                RAISE EXCEPTION 'Cannot downgrade: ALA, MDC or UNIVERSAL players require manual reassignment first';
            END IF;
        END $$
    """)
    op.execute("CREATE TYPE player_position_old AS ENUM ('GOALKEEPER', 'DEFENDER', 'MIDFIELDER', 'FORWARD')")
    op.execute("""
        ALTER TABLE players ALTER COLUMN position TYPE player_position_old
        USING (CASE position::text
            WHEN 'GR' THEN 'GOALKEEPER'
            WHEN 'DC' THEN 'DEFENDER'
            WHEN 'MC' THEN 'MIDFIELDER'
            WHEN 'PL' THEN 'FORWARD'
        END)::player_position_old
    """)
    op.execute("DROP TYPE player_position")
    op.execute("ALTER TYPE player_position_old RENAME TO player_position")
